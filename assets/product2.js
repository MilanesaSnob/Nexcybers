  function buildCompass() {
    const wrap = document.getElementById('cmps');
    if (!wrap) return;
    const ns = 'http://www.w3.org/2000/svg', C = 100;
    const el = (t, a) => { const n = document.createElementNS(ns, t); for (const k in a) n.setAttribute(k, a[k]); return n; };
    const ticks = document.getElementById('cmps-ticks');
    if (ticks && !ticks.childNodes.length) {
      for (let d = 0; d < 360; d += 5) {
        const a = (d - 90) * Math.PI / 180, major = d % 30 === 0;
        const r1 = major ? 80 : 84, r2 = 90;
        ticks.appendChild(el('line', { x1: C + r1 * Math.cos(a), y1: C + r1 * Math.sin(a), x2: C + r2 * Math.cos(a), y2: C + r2 * Math.sin(a), class: major ? 'cmps-tick major' : 'cmps-tick' }));
      }
    }
    if (wrap.dataset.bound) return;
    wrap.dataset.bound = '1';
    const needle = document.getElementById('cmps-needle'), read = document.getElementById('cmps-deg');
    wrap.classList.add('is-idle');
    let pending = null;
    const apply = () => {
      pending = null;
      const r = wrap.getBoundingClientRect();
      if (!r.width) return;
      const cx = r.left + r.width / 2, cy = r.top + r.height / 2;
      const deg = (Math.atan2(last.y - cy, last.x - cx) * 180 / Math.PI + 90 + 360) % 360;
      wrap.classList.remove('is-idle');
      needle.style.transform = 'rotate(' + deg.toFixed(1) + 'deg)';
      read.textContent = String(Math.round(deg)).padStart(3, '0');
    };
    const last = { x: 0, y: 0 };
    window.addEventListener('pointermove', e => {
      last.x = e.clientX; last.y = e.clientY;
      if (!pending) pending = requestAnimationFrame(apply);
    }, { passive: true });
    document.addEventListener('pointerleave', () => {
      wrap.classList.add('is-idle');
      needle.style.transform = '';
      read.textContent = '000';
    });
  }

